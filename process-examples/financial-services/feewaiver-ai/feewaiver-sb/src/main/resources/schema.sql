-- analysis_entity table for Spring Data JDBC (co.summit58.feewaiver.sb.entities.AnalysisEntity).
-- Same table and column names that Hibernate generated previously, so existing H2 databases keep working.
CREATE TABLE IF NOT EXISTS analysis_entity (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_text            CLOB NOT NULL,
    prior_fee_waiver_count  INTEGER NOT NULL,
    fee_amount              NUMERIC(12, 2) NOT NULL,
    vulnerable_customer     BOOLEAN NOT NULL,
    regulatory_sensitivity  BOOLEAN NOT NULL,
    ai_case_summary         CLOB,
    ai_intent               VARCHAR(255),
    ai_risk_level           VARCHAR(255),
    ai_confidence           DOUBLE PRECISION,
    ai_recommended_action   VARCHAR(255),
    ai_reasoning_summary    CLOB,
    policy_flags_json       CLOB NOT NULL,
    requires_human_review   BOOLEAN NOT NULL,
    policy_route            VARCHAR(255) NOT NULL,
    final_action            VARCHAR(255) NOT NULL,
    triggered_policies_json CLOB NOT NULL,
    policy_explanation      CLOB,
    created_at              TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    review_status           VARCHAR(255),
    review_decision         VARCHAR(255),
    reviewer                VARCHAR(255),
    review_notes            CLOB,
    reviewed_at             TIMESTAMP(6) WITH TIME ZONE,
    resolution_status       VARCHAR(255),
    drl_escalate            BOOLEAN,
    drl_requires_review     BOOLEAN,
    drl_reason              CLOB
);
